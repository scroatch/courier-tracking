CREATE TABLE courier
(
    id                    VARCHAR(64)              NOT NULL,
    last_lat              DOUBLE PRECISION         NOT NULL,
    last_lng              DOUBLE PRECISION         NOT NULL,
    last_recorded_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    total_distance_meters DOUBLE PRECISION         NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_courier PRIMARY KEY (id)
);

CREATE TABLE courier_location
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    courier_id              VARCHAR(64)              NOT NULL,
    lat                     DOUBLE PRECISION         NOT NULL,
    lng                     DOUBLE PRECISION         NOT NULL,
    recorded_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    out_of_order            BOOLEAN                  NOT NULL,
    segment_distance_meters DOUBLE PRECISION,
    CONSTRAINT pk_courier_location PRIMARY KEY (id),
    CONSTRAINT fk_courier_location_courier FOREIGN KEY (courier_id) REFERENCES courier (id),
    CONSTRAINT uk_courier_location_courier_recorded_at UNIQUE (courier_id, recorded_at)
);

CREATE TABLE courier_store_presence
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    courier_id   VARCHAR(64)              NOT NULL,
    store_name   VARCHAR(128)             NOT NULL,
    inside       BOOLEAN                  NOT NULL,
    last_exit_at TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_courier_store_presence PRIMARY KEY (id),
    CONSTRAINT fk_courier_store_presence_courier FOREIGN KEY (courier_id) REFERENCES courier (id),
    CONSTRAINT uk_courier_store_presence_courier_store UNIQUE (courier_id, store_name)
);

CREATE TABLE store_entrance
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    courier_id  VARCHAR(64)              NOT NULL,
    store_name  VARCHAR(128)             NOT NULL,
    location_id BIGINT                   NOT NULL,
    entered_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_store_entrance PRIMARY KEY (id),
    CONSTRAINT fk_store_entrance_courier FOREIGN KEY (courier_id) REFERENCES courier (id),
    CONSTRAINT fk_store_entrance_location FOREIGN KEY (location_id) REFERENCES courier_location (id)
);

CREATE INDEX idx_store_entrance_courier_entered_at ON store_entrance (courier_id, entered_at);